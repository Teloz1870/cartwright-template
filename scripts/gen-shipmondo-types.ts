/**
 * Generate the Shipmondo API types the `shipmondo` plugin compiles against.
 *
 * Shipmondo publishes its OpenAPI 3 spec at
 *   https://sandbox.shipmondo.com/api/public/v3/elements.json
 * (the same document behind https://shipmondo.dev/api-reference). The whole
 * spec yields ~11 000 lines of types for 81 endpoints, and every scaffold that
 * keeps the plugin would carry them, so this keeps only the endpoints the
 * plugin calls (PATHS below) and the schemas they reach.
 *
 *   pnpm gen:shipmondo-types                 # regenerate from the committed subset
 *   pnpm gen:shipmondo-types --refresh <file> # re-cut the subset from a downloaded full spec
 *
 * The committed subset (plugins/shipmondo/openapi/shipmondo-v3.subset.json) is
 * the input, so a regeneration needs no network and gives the same file:
 * tests/unit/shipmondo/types-drift.test.ts fails when the two drift apart.
 * Owner choice 2026-10-05: openapi-typescript from the official spec. It runs
 * pinned through `pnpm dlx` rather than as a devDependency: installing it moves
 * the whole tree's `supports-color` from 8 to 10 (next, babel, eslint, gaxios
 * among them), a production-wide change for a generator that runs by hand.
 * So the drift test checks the subset's hash in the header, not a re-render.
 */
export const GENERATOR = "openapi-typescript@7.13.0";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SUBSET = join(ROOT, "plugins/shipmondo/openapi/shipmondo-v3.subset.json");
const OUT = join(ROOT, "plugins/shipmondo/lib/api.d.ts");

/** The endpoints the plugin calls. Add one here, then run with --refresh. */
export const PATHS: Record<string, readonly string[]> = {
  "/pickup_points": ["get"],
  "/sales_orders": ["get", "post"],
  "/sales_orders/{id}": ["get"],
  "/shipments/{id}": ["get"],
  "/webhooks": ["get", "post"],
};

type Json = Record<string, unknown>;

/** The full spec cut down to PATHS and every component they reference. */
export function cutSubset(spec: Json): Json {
  const paths = spec.paths as Record<string, Json>;
  const components = (spec.components ?? {}) as Record<string, Record<string, unknown>>;
  const keptPaths: Record<string, Json> = {};
  for (const [path, methods] of Object.entries(PATHS)) {
    const item = paths[path];
    if (!item) throw new Error(`Shipmondo spec has no path ${path}`);
    keptPaths[path] = Object.fromEntries(
      methods.map((m) => {
        if (!item[m]) throw new Error(`Shipmondo spec has no ${m.toUpperCase()} ${path}`);
        return [m, item[m]];
      }),
    );
  }

  const kept = new Map<string, Set<string>>();
  const visit = (node: unknown): void => {
    if (Array.isArray(node)) return node.forEach(visit);
    if (!node || typeof node !== "object") return;
    for (const [key, value] of Object.entries(node)) {
      if (key === "$ref" && typeof value === "string" && value.startsWith("#/components/")) {
        const [, , section, name] = value.split("/");
        const seen = kept.get(section) ?? new Set<string>();
        kept.set(section, seen);
        if (seen.has(name)) continue;
        seen.add(name);
        visit(components[section]?.[name]);
      } else {
        visit(value);
      }
    }
  };
  visit(keptPaths);

  const keptComponents: Record<string, Record<string, unknown>> = {};
  for (const section of [...kept.keys()].sort()) {
    keptComponents[section] = Object.fromEntries(
      [...(kept.get(section) ?? [])].sort().map((name) => [name, components[section][name]]),
    );
  }
  // Security schemes are referenced by name, not $ref, so they are kept — without
  // their prose, which carries sample API credentials into the public mirror.
  if (components.securitySchemes) {
    keptComponents.securitySchemes = Object.fromEntries(
      Object.entries(components.securitySchemes).map(([name, scheme]) => {
        const { description: _description, ...rest } = scheme as Json;
        return [name, rest];
      }),
    );
  }

  return {
    openapi: spec.openapi,
    info: spec.info,
    servers: spec.servers,
    paths: keptPaths,
    components: keptComponents,
  };
}

export function subsetHash(subsetJson: string): string {
  return createHash("sha256").update(subsetJson).digest("hex");
}

/** The header that binds api.d.ts to the subset it was generated from. */
export function header(subsetJson: string): string {
  return (
    "// GENERATED by scripts/gen-shipmondo-types.ts from plugins/shipmondo/openapi/shipmondo-v3.subset.json.\n" +
    `// Generator: ${GENERATOR} --alphabetize --default-non-nullable=false\n` +
    `// Subset sha256: ${subsetHash(subsetJson)}\n` +
    "// Do not edit by hand: change PATHS in the script and regenerate.\n\n"
  );
}

function renderTypes(subsetPath: string, subsetJson: string): string {
  const out = join(mkdtempSync(join(tmpdir(), "shipmondo-types-")), "api.d.ts");
  // defaultNonNullable off: a field with a default is one Shipmondo fills in
  // itself, so a request may leave it out.
  const run = spawnSync(
    "pnpm",
    ["dlx", GENERATOR, subsetPath, "--alphabetize", "--default-non-nullable=false", "-o", out],
    { stdio: "inherit" },
  );
  if (run.status !== 0) throw new Error(`${GENERATOR} failed (exit ${run.status})`);
  return header(subsetJson) + readFileSync(out, "utf8");
}

async function main() {
  const refresh = process.argv.indexOf("--refresh");
  if (refresh !== -1) {
    const full = JSON.parse(readFileSync(process.argv[refresh + 1], "utf8")) as Json;
    writeFileSync(SUBSET, `${JSON.stringify(cutSubset(full), null, 2)}\n`);
    console.log(`[gen:shipmondo-types] wrote ${SUBSET}`);
  }
  writeFileSync(OUT, renderTypes(SUBSET, readFileSync(SUBSET, "utf8")));
  console.log(`[gen:shipmondo-types] wrote ${OUT}`);
}

// Run when invoked directly (not when imported by the drift test).
if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
